//! Procedural derives for Lily's typed ClickHouse adapters.
//!
//! Applications normally import these derives from `lily_clickhouse`; a direct
//! dependency on this proc-macro crate is unnecessary.
//!
//! [`ClickhouseSchema`] is the entity metadata layer. [`ClickhouseTable`]
//! generates a typed table API and its DI lifecycle. [`ClickhouseRepository`]
//! is an optional convenience delegating to that table; a domain service may
//! inject the generated table directly instead.
//!
//! # Single mode
//!
//! ```ignore
//! #[derive(Injectable, ClickhouseTable, Default)]
//! #[entity_type(AuditEvent)]
//! #[service(lifetime = "Singleton")]
//! struct AuditTable {
//!     #[inject]
//!     db: Arc<DatabaseService>,
//! }
//! ```
//!
//! # Factory mode
//!
//! Factory tables additionally declare `#[cell_name("analytics")]`, inject a
//! field named `clickhouse_factory: Arc<ClickhouseFactory>`, and retain an
//! unannotated `db: Arc<DatabaseService>` field. The generated initializer
//! selects the named cell and assigns `db`.
//!
//! Both table and repository derives implement `lily_injection::ServiceTrait`.
//! Do not supply a competing manual implementation.

