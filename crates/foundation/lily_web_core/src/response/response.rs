pin_project_lite::pin_project! {
    struct ErasedResponseStreamState<S> {
        #[pin]
        source: S,
        exact_length: Option<u64>,
        max_chunk_bytes: usize,
        max_total_bytes: Option<u64>,
        pending: Bytes,
        accepted_bytes: u64,
        emitted_bytes: u64,
        terminal: bool,
    }
}

impl<S> ErasedResponseStreamState<S> {
    fn new(source: S) -> Self {
        Self {
            source,
            exact_length: None,
            max_chunk_bytes: usize::MAX,
            max_total_bytes: None,
            pending: Bytes::new(),
            accepted_bytes: 0,
            emitted_bytes: 0,
            terminal: false,
        }
    }
}

impl<S> ErasedResponseStream for ErasedResponseStreamState<S>
where
    S: Stream<Item = Result<Bytes, ResponseBodyError>> + Send + 'static,
{
    fn set_exact_length(self: Pin<&mut Self>, exact_length: Option<u64>) {
        *self.project().exact_length = exact_length;
    }

    fn set_max_chunk_bytes(self: Pin<&mut Self>, max_chunk_bytes: usize) {
        *self.project().max_chunk_bytes = max_chunk_bytes;
    }

    fn set_max_total_bytes(self: Pin<&mut Self>, max_total_bytes: Option<u64>) {
        *self.project().max_total_bytes = max_total_bytes;
    }

    fn apply_server_limits(self: Pin<&mut Self>, limits: ResponseStreamingLimits) {
        let this = self.project();
        *this.max_chunk_bytes = (*this.max_chunk_bytes).min(limits.max_chunk_bytes());
        *this.max_total_bytes =
            narrow_optional_limit(*this.max_total_bytes, limits.max_total_bytes());
    }

    fn exact_length(&self) -> Option<u64> {
        self.exact_length
    }

    fn max_chunk_bytes(&self) -> usize {
        self.max_chunk_bytes
    }

    fn max_total_bytes(&self) -> Option<u64> {
        self.max_total_bytes
    }

    fn emitted_bytes(&self) -> u64 {
        self.emitted_bytes
    }

    fn poll_bounded_chunk(
        self: Pin<&mut Self>,
        context: &mut Context<'_>,
        max_frame_bytes: usize,
    ) -> Poll<Option<Result<Bytes, ResponseBodyError>>> {
        const MAX_EMPTY_CHUNKS_PER_POLL: usize = 16;
        let mut this = self.project();
        if *this.terminal {
            return Poll::Ready(None);
        }

        let mut empty_chunks = 0usize;
        loop {
            if !this.pending.is_empty() {
                let length = this.pending.len().min(max_frame_bytes);
                let frame = this.pending.split_to(length);
                *this.emitted_bytes = this.emitted_bytes.saturating_add(length as u64);
                return Poll::Ready(Some(Ok(frame)));
            }

            match this.source.as_mut().poll_next(context) {
                Poll::Pending => return Poll::Pending,
                Poll::Ready(Some(Ok(chunk))) if chunk.is_empty() => {
                    empty_chunks += 1;
                    if empty_chunks == MAX_EMPTY_CHUNKS_PER_POLL {
                        context.waker().wake_by_ref();
                        return Poll::Pending;
                    }
                }
                Poll::Ready(Some(Ok(chunk))) => {
                    if chunk.len() > *this.max_chunk_bytes {
                        *this.terminal = true;
                        return Poll::Ready(Some(Err(ResponseBodyError::StreamChunkTooLarge {
                            limit_bytes: *this.max_chunk_bytes,
                        })));
                    }
                    let chunk_bytes = u64::try_from(chunk.len()).unwrap_or(u64::MAX);
                    let next = match this.accepted_bytes.checked_add(chunk_bytes) {
                        Some(next) => next,
                        None => {
                            *this.terminal = true;
                            return Poll::Ready(Some(Err(
                                ResponseBodyError::StreamLimitExceeded {
                                    limit_bytes: this.max_total_bytes.unwrap_or(u64::MAX),
                                },
                            )));
                        }
                    };
                    if let Some(limit_bytes) = *this.max_total_bytes {
                        if next > limit_bytes {
                            *this.terminal = true;
                            return Poll::Ready(Some(Err(
                                ResponseBodyError::StreamLimitExceeded { limit_bytes },
                            )));
                        }
                    }
                    if let Some(expected_bytes) = *this.exact_length {
                        if next > expected_bytes {
                            *this.terminal = true;
                            return Poll::Ready(Some(Err(
                                ResponseBodyError::StreamLengthExceeded { expected_bytes },
                            )));
                        }
                    }
                    *this.accepted_bytes = next;
                    *this.pending = chunk;
                }
                Poll::Ready(Some(Err(error))) => {
                    *this.terminal = true;
                    return Poll::Ready(Some(Err(error)));
                }
                Poll::Ready(None) => {
                    *this.terminal = true;
                    if let Some(expected_bytes) = *this.exact_length {
                        if *this.accepted_bytes != expected_bytes {
                            return Poll::Ready(Some(Err(
                                ResponseBodyError::StreamLengthIncomplete {
                                    expected_bytes,
                                    actual_bytes: *this.accepted_bytes,
                                },
                            )));
                        }
                    }
                    return Poll::Ready(None);
                }
            }
        }
    }
}

const fn narrow_optional_limit(left: Option<u64>, right: Option<u64>) -> Option<u64> {
    match (left, right) {
        (Some(left), Some(right)) => Some(if left < right { left } else { right }),
        (Some(value), None) | (None, Some(value)) => Some(value),
        (None, None) => None,
    }
}

struct BufferedResponseBody {
    budget: BodyBudget,
    data: Vec<u8>,
    failure: Option<ResponseBodyError>,
}

impl BufferedResponseBody {
    fn new(budget: BodyBudget) -> Self {
        Self {
            budget,
            data: Vec::new(),
            failure: None,
        }
    }

    fn first_failure(&self) -> Option<ResponseBodyError> {
        self.failure
    }

    fn poison(&mut self, error: ResponseBodyError) -> ResponseBodyError {
        self.data.zeroize();
        self.data.clear();
        *self.failure.get_or_insert(error)
    }

    fn ensure_writable(&self) -> Result<(), ResponseBodyError> {
        self.failure.map_or(Ok(()), Err)
    }

    fn try_replace_vec(&mut self, data: Vec<u8>) -> Result<(), ResponseBodyError> {
        self.ensure_writable()?;
        if let Err(error) = self.budget.ensure_length(data.len()) {
            return Err(self.poison(error.into()));
        }
        self.data.zeroize();
        self.data = data;
        Ok(())
    }

    fn try_replace_slice(&mut self, data: &[u8]) -> Result<(), ResponseBodyError> {
        self.ensure_writable()?;
        if let Err(error) = self.budget.ensure_length(data.len()) {
            return Err(self.poison(error.into()));
        }
        let mut replacement = Vec::new();
        if replacement.try_reserve_exact(data.len()).is_err() {
            return Err(self.poison(ResponseBodyError::AllocationFailed {
                limit_bytes: self.budget.limit_bytes(),
            }));
        }
        replacement.extend_from_slice(data);
        self.data.zeroize();
        self.data = replacement;
        Ok(())
    }

    fn try_extend_from_slice(&mut self, data: &[u8]) -> Result<(), ResponseBodyError> {
        self.ensure_writable()?;
        if let Err(error) = self.budget.checked_next_length(self.data.len(), data.len()) {
            return Err(self.poison(error.into()));
        }
        if self.data.try_reserve_exact(data.len()).is_err() {
            return Err(self.poison(ResponseBodyError::AllocationFailed {
                limit_bytes: self.budget.limit_bytes(),
            }));
        }
        self.data.extend_from_slice(data);
        Ok(())
    }

    fn into_bytes(mut self) -> Result<Bytes, ResponseBodyError> {
        if let Some(error) = self.failure {
            return Err(error);
        }
        Ok(Bytes::from(std::mem::take(&mut self.data)))
    }
}

impl Drop for BufferedResponseBody {
    fn drop(&mut self) {
        self.data.zeroize();
    }
}

/// Allocation-aware serializer target. It is crate-private because response
/// converters, not application handlers, own serialization policy.
pub(crate) struct BoundedBodyWriter {
    body: BufferedResponseBody,
}

impl BoundedBodyWriter {
    pub(crate) fn new(budget: BodyBudget) -> Self {
        Self {
            body: BufferedResponseBody::new(budget),
        }
    }

    pub(crate) fn failure(&self) -> Option<ResponseBodyError> {
        self.body.first_failure()
    }

    pub(crate) fn finish(mut self) -> Result<Vec<u8>, ResponseBodyError> {
        self.body.ensure_writable()?;
        Ok(std::mem::take(&mut self.body.data))
    }
}

impl std::io::Write for BoundedBodyWriter {
    fn write(&mut self, bytes: &[u8]) -> std::io::Result<usize> {
        self.body
            .try_extend_from_slice(bytes)
            .map_err(|error| std::io::Error::other(error.to_string()))?;
        Ok(bytes.len())
    }

    fn flush(&mut self) -> std::io::Result<()> {
        Ok(())
    }
}

struct StatusMessage {
    code: usize,
    msg: &'static str,
}

/// Protocol-neutral response snapshot consumed by HTTP transport adapters.
#[derive(Debug)]
#[doc(hidden)]
pub struct TransportResponseParts {
    pub status: u16,
    pub headers: Vec<(String, String)>,
    /// Retains the established buffered transport snapshot for non-streaming responses.
    pub body: Bytes,
    /// Present only when the closed application body model selected streaming.
    pub stream: Option<ResponseBodyStream>,
}

impl TransportResponseParts {
    #[must_use]
    pub fn exact_length(&self) -> Option<u64> {
        self.stream.as_ref().map_or_else(
            || Some(self.body.len() as u64),
            ResponseBodyStream::exact_length,
        )
    }

    #[must_use]
    pub fn into_body(self) -> TransportResponseBody {
        self.stream.map_or_else(
            || TransportResponseBody::Full(self.body),
            TransportResponseBody::Stream,
        )
    }
}

/// Protocol-neutral body selected by the application response boundary.
#[doc(hidden)]
#[derive(Debug)]
pub enum TransportResponseBody {
    Full(Bytes),
    Stream(ResponseBodyStream),
}

impl Default for TransportResponseBody {
    fn default() -> Self {
        Self::Full(Bytes::new())
    }
}

impl From<Bytes> for TransportResponseBody {
    fn from(body: Bytes) -> Self {
        Self::Full(body)
    }
}

impl TransportResponseBody {
    #[must_use]
    pub fn exact_length(&self) -> Option<u64> {
        match self {
            Self::Full(body) => Some(body.len() as u64),
            Self::Stream(body) => body.exact_length(),
        }
    }

    #[must_use]
    pub const fn is_streaming(&self) -> bool {
        matches!(self, Self::Stream(_))
    }

    /// Returns the buffered representation length without treating an exact
    /// streaming declaration as bytes already observed by transport.
    #[must_use]
    pub const fn buffered_length(&self) -> Option<usize> {
        match self {
            Self::Full(body) => Some(body.len()),
            Self::Stream(_) => None,
        }
    }

    #[must_use]
    pub fn empty() -> Self {
        Self::Full(Bytes::new())
    }
}

impl Response {
    /// Creates a new response builder.
    pub fn builder() -> ResponseBuilder {
        ResponseBuilder::new()
    }

    /// Creates an empty `200 OK` response with default limits.
    pub async fn new() -> Result<Self, HttpApiError> {
        Self::with_limits(ResponseLimits::default()).await
    }

    /// Creates a response from one immutable effective limit snapshot.
    pub async fn with_limits(limits: ResponseLimits) -> Result<Self, HttpApiError> {
        Ok(Self::from_limits(limits))
    }

    /// Creates an empty response without performing any fallible work.
    #[must_use]
    pub fn from_limits(limits: ResponseLimits) -> Self {
        Self {
            headers: SmallVec::new(),
            header_bytes: 0,
            status_message: StatusMessage {
                code: 200,
                msg: "OK",
            },
            limits,
            body: ResponseBody::Full(BufferedResponseBody::new(limits.body_budget())),
        }
    }

    #[must_use]
    /// Returns the immutable effective response limits.
    pub const fn limits(&self) -> ResponseLimits {
        self.limits
    }

    #[must_use]
    /// Returns the effective buffered-body budget.
    pub const fn body_budget(&self) -> BodyBudget {
        self.limits.body_budget()
    }

    /// Returns the response's current HTTP status code.
    #[inline]
    pub fn status_code_value(&self) -> u16 {
        self.status_message.code as u16
    }

    /// Sets the status code.
    pub fn status(&mut self, code: u16, reason: &'static str) -> &mut Self {
        self.status_message.code = code as usize;
        self.status_message.msg = reason;
        self
    }

    /// Sets a static text body and its authoritative content type.
    pub fn text(&mut self, text: &'static str) -> Result<&mut Self, ResponseWriteError> {
        self.try_insert_header("Content-Type", "text/plain")?;
        self.body.full_mut()?.try_replace_slice(text.as_bytes())?;
        Ok(self)
    }

    /// Sets a body from an owned byte vector.
    pub fn set_body_vec(&mut self, data: Vec<u8>) -> Result<&mut Self, ResponseBodyError> {
        self.body.full_mut()?.try_replace_vec(data)?;
        Ok(self)
    }

    #[inline]
    /// Sets status metadata for Lily's application and middleware runtime.
    #[doc(hidden)]
    pub fn status_code(&mut self, code: usize, msg: &'static str) -> &mut Self {
        self.status_message = StatusMessage { code, msg };
        self
    }

    /// Atomically replaces the complete buffered application response.
    ///
    /// All headers are parsed and bounded before any existing status, header,
    /// or body state is changed. Response converters use this as their single
    /// terminal commit point so a failed conversion cannot leave a partial
    /// success response behind.
    pub(super) fn replace_buffered<'a, I>(
        &mut self,
        status: u16,
        reason: &'static str,
        headers: I,
        body: Vec<u8>,
    ) -> Result<(), ResponseWriteError>
    where
        I: IntoIterator<Item = (&'a str, &'a str)>,
    {
        if let Err(error) = self.limits.body_budget().ensure_length(body.len()) {
            let error = ResponseBodyError::from(error);
            if let Ok(current) = self.body.full_mut() {
                current.poison(error);
            }
            return Err(error.into());
        }
        if let ResponseBody::Full(current) = &self.body {
            current.ensure_writable()?;
        }
        let (prepared_headers, prepared_header_bytes) = prepare_headers(self.limits, headers)?;
        let mut replacement = BufferedResponseBody::new(self.limits.body_budget());
        replacement.try_replace_vec(body)?;

        self.headers = prepared_headers;
        self.header_bytes = prepared_header_bytes;
        self.status_message = StatusMessage {
            code: usize::from(status),
            msg: reason,
        };
        self.body = ResponseBody::Full(replacement);
        Ok(())
    }

    /// Atomically replaces the complete response with one lazy stream.
    pub(super) fn replace_streaming<'a, I>(
        &mut self,
        status: u16,
        reason: &'static str,
        headers: I,
        mut body: ResponseBodyStream,
    ) -> Result<(), ResponseWriteError>
    where
        I: IntoIterator<Item = (&'a str, &'a str)>,
    {
        if let ResponseBody::Full(current) = &self.body {
            current.ensure_writable()?;
        }
        if body.max_chunk_bytes() == 0 {
            return Err(ResponseBodyError::InvalidStreamChunkLimit.into());
        }
        if matches!(body.max_total_bytes(), Some(0)) {
            return Err(ResponseBodyError::InvalidStreamTotalLimit.into());
        }
        body.apply_server_limits(self.limits.streaming());
        if body
            .exact_length()
            .zip(body.max_total_bytes())
            .is_some_and(|(exact, maximum)| exact > maximum)
        {
            return Err(ResponseBodyError::StreamLimitExceeded {
                limit_bytes: body.max_total_bytes().expect("checked optional limit"),
            }
            .into());
        }
        let (prepared_headers, prepared_header_bytes) = prepare_headers(self.limits, headers)?;

        self.headers = prepared_headers;
        self.header_bytes = prepared_header_bytes;
        self.status_message = StatusMessage {
            code: usize::from(status),
            msg: reason,
        };
        self.body = ResponseBody::Stream(body);
        Ok(())
    }

    /// Appends one typed, validated `Set-Cookie` field line.
    #[inline]
    pub fn set_cookie(
        &mut self,
        cookie: &ResponseCookie,
    ) -> Result<&mut Self, ResponseCookieWriteError> {
        let value = cookie.to_header_value()?;
        self.try_append_header("Set-Cookie", &value)
            .map_err(ResponseCookieWriteError::from)
    }

    /// Appends one typed cookie signed with the key ring's primary key.
    #[inline]
    pub fn set_signed_cookie(
        &mut self,
        cookie: &ResponseCookie,
        key_ring: &CookieKeyRing,
    ) -> Result<&mut Self, ResponseCookieWriteError> {
        let value = cookie.to_signed_header_value(key_ring)?;
        self.try_append_header("Set-Cookie", &value)
            .map_err(ResponseCookieWriteError::from)
    }

    /// Appends one typed cookie encrypted and authenticated with the primary key.
    #[inline]
    pub fn set_private_cookie(
        &mut self,
        cookie: &ResponseCookie,
        key_ring: &CookieKeyRing,
    ) -> Result<&mut Self, ResponseCookieWriteError> {
        let value = cookie.to_private_header_value(key_ring)?;
        self.try_append_header("Set-Cookie", &value)
            .map_err(ResponseCookieWriteError::from)
    }

    /// Appends a cookie removal field with an empty value, `Max-Age=0`, and a
    /// past `Expires` timestamp. The removal scope must match the original
    /// cookie's path/domain.
    #[inline]
    pub fn delete_cookie(
        &mut self,
        removal: &CookieRemoval,
    ) -> Result<&mut Self, ResponseCookieWriteError> {
        let value = removal.to_header_value()?;
        self.try_append_header("Set-Cookie", &value)
            .map_err(ResponseCookieWriteError::from)
    }

    /// Deletes a signed cookie. Removal fields intentionally carry no secret payload.
    #[inline]
    pub fn delete_signed_cookie(
        &mut self,
        removal: &CookieRemoval,
    ) -> Result<&mut Self, ResponseCookieWriteError> {
        self.delete_cookie(removal)
    }

    /// Deletes a private cookie. Removal fields intentionally carry no secret payload.
    #[inline]
    pub fn delete_private_cookie(
        &mut self,
        removal: &CookieRemoval,
    ) -> Result<&mut Self, ResponseCookieWriteError> {
        self.delete_cookie(removal)
    }

    /// Returns the first application-managed value for a valid header name.
    ///
    /// Use [`Self::header_values`] when every value of a repeatable field,
    /// such as `Set-Cookie`, is needed.
    #[inline]
    pub fn header(&self, name: &str) -> Option<&str> {
        let name = parse_header_name(name).ok()?;
        self.headers
            .iter()
            .find(|header| header.name == name)
            .map(|header| {
                std::str::from_utf8(header.value.as_bytes())
                    .expect("response header values originate from UTF-8 strings")
            })
    }

    /// Returns every application-managed value for a valid header name.
    ///
    /// The name is validated with the same policy as header mutation. Values
    /// borrow the response storage, so inspecting repeatable fields does not
    /// clone their contents.
    pub fn header_values<'a>(
        &'a self,
        name: &str,
    ) -> Result<impl Iterator<Item = &'a str> + 'a, ResponseHeaderError> {
        let name = parse_header_name(name)?;
        ensure_application_managed_header(&name)?;
        Ok(self
            .headers
            .iter()
            .filter(move |header| header.name == name)
            .map(|header| {
                std::str::from_utf8(header.value.as_bytes())
                    .expect("response header values originate from UTF-8 strings")
            }))
    }

    /// Checks for an application-managed header using case-insensitive HTTP
    /// name rules.
    ///
    /// Invalid names are reported instead of being confused with an absent
    /// header.
    #[inline]
    pub fn contains_header(&self, name: &str) -> Result<bool, ResponseHeaderError> {
        let name = parse_header_name(name)?;
        ensure_application_managed_header(&name)?;
        Ok(self.headers.iter().any(|header| header.name == name))
    }

    /// Backward-compatible application-header lookup that treats an invalid,
    /// transport-controlled, or hop-by-hop name as absent.
    #[inline]
    pub fn has_header(&self, name: &str) -> bool {
        self.contains_header(name).unwrap_or(false)
    }

    /// Inserts a validated field, replacing every existing value with the
    /// same case-insensitive name.
    ///
    /// Validation and limit checks complete before mutation, so an error
    /// leaves the response unchanged. Transport-controlled and hop-by-hop
    /// fields are rejected rather than silently changed by the transport.
    pub fn try_insert_header(
        &mut self,
        name: &str,
        value: &str,
    ) -> Result<&mut Self, ResponseHeaderError> {
        let (name, value, wire_bytes) =
            validate_header(name, value, self.limits.max_header_bytes())?;
        let mut removed_count = 0usize;
        let mut removed_bytes = 0usize;
        for header in &self.headers {
            if header.name == name {
                removed_count += 1;
                removed_bytes = removed_bytes.checked_add(header.wire_bytes).ok_or(
                    ResponseHeaderError::HeadersTooLarge {
                        limit_bytes: self.limits.max_header_bytes(),
                    },
                )?;
            }
        }

        let next_count = self
            .headers
            .len()
            .checked_sub(removed_count)
            .and_then(|count| count.checked_add(1))
            .ok_or(ResponseHeaderError::TooManyHeaders {
                limit: self.limits.max_header_count(),
            })?;
        ensure_header_count(next_count, self.limits.max_header_count())?;
        let next_bytes = self
            .header_bytes
            .checked_sub(removed_bytes)
            .and_then(|bytes| bytes.checked_add(wire_bytes))
            .ok_or(ResponseHeaderError::HeadersTooLarge {
                limit_bytes: self.limits.max_header_bytes(),
            })?;
        ensure_header_bytes(next_bytes, self.limits.max_header_bytes())?;

        self.headers.retain(|header| header.name != name);
        self.headers.push(StoredHeader {
            name,
            value,
            wire_bytes,
        });
        self.header_bytes = next_bytes;
        Ok(self)
    }

    /// Appends a validated field line.
    ///
    /// Known singleton fields reject duplicates. Extension fields and
    /// standards-defined repeatable fields remain appendable; callers can use
    /// [`Self::try_insert_header`] when authoritative replacement is desired.
    /// Transport-controlled and hop-by-hop fields are rejected.
    pub fn try_append_header(
        &mut self,
        name: &str,
        value: &str,
    ) -> Result<&mut Self, ResponseHeaderError> {
        let (name, value, wire_bytes) =
            validate_header(name, value, self.limits.max_header_bytes())?;
        if self.headers.iter().any(|header| header.name == name)
            && is_singleton_response_header(&name)
        {
            return Err(ResponseHeaderError::DuplicateSingleton);
        }

        let next_count =
            self.headers
                .len()
                .checked_add(1)
                .ok_or(ResponseHeaderError::TooManyHeaders {
                    limit: self.limits.max_header_count(),
                })?;
        ensure_header_count(next_count, self.limits.max_header_count())?;
        let next_bytes = self.header_bytes.checked_add(wire_bytes).ok_or(
            ResponseHeaderError::HeadersTooLarge {
                limit_bytes: self.limits.max_header_bytes(),
            },
        )?;
        ensure_header_bytes(next_bytes, self.limits.max_header_bytes())?;

        self.headers.push(StoredHeader {
            name,
            value,
            wire_bytes,
        });
        self.header_bytes = next_bytes;
        Ok(self)
    }

    /// Removes every application-managed field with the supplied
    /// case-insensitive name.
    pub fn remove_header(&mut self, name: &str) -> Result<usize, ResponseHeaderError> {
        let name = parse_header_name(name)?;
        ensure_application_managed_header(&name)?;
        let previous_count = self.headers.len();
        let mut removed_bytes = 0usize;
        self.headers.retain(|header| {
            if header.name == name {
                removed_bytes += header.wire_bytes;
                false
            } else {
                true
            }
        });
        self.header_bytes -= removed_bytes;
        Ok(previous_count - self.headers.len())
    }

    /// Compatibility alias for append semantics.
    ///
    /// Unlike the former API this method is fallible, so invalid or oversized
    /// data cannot be accepted silently.
    #[deprecated(note = "use try_insert_header or try_append_header to state duplicate intent")]
    pub fn add_header(
        &mut self,
        name: &str,
        value: &str,
    ) -> Result<&mut Self, ResponseHeaderError> {
        self.try_append_header(name, value)
    }

    /// Replaces the body from a static string under the effective budget.
    #[inline]
    pub fn body(&mut self, value: &'static str) -> Result<&mut Self, ResponseBodyError> {
        self.body.full_mut()?.try_replace_slice(value.as_bytes())?;
        Ok(self)
    }

    /// Replaces the body from an owned vector without a transport handoff copy.
    #[inline]
    pub fn body_vec(&mut self, value: Vec<u8>) -> Result<&mut Self, ResponseBodyError> {
        self.set_body_vec(value)
    }

    /// Appends bytes after checking length arithmetic and the effective limit.
    #[inline]
    pub fn write_body(&mut self, value: &[u8]) -> Result<&mut Self, ResponseBodyError> {
        self.body.full_mut()?.try_extend_from_slice(value)?;
        Ok(self)
    }

    /// Returns the first terminal body failure, if application code ignored a
    /// fallible mutation result.
    #[must_use]
    pub fn body_failure(&self) -> Option<ResponseBodyError> {
        self.body.first_failure()
    }

    pub(crate) fn record_body_failure(&mut self, error: ResponseBodyError) {
        if let Ok(body) = self.body.full_mut() {
            if body.first_failure().is_none() {
                body.poison(error);
            }
        }
    }

    /// Returns response metadata without HTTP/1.1 framing.
    ///
    /// All headers have already passed syntax, duplicate, count, and byte
    /// limit checks. The transport never receives an unvalidated field.
    #[doc(hidden)]
    pub fn into_transport_parts(self) -> Result<TransportResponseParts, ResponseBodyError> {
        if let Some(error) = self.body.first_failure() {
            return Err(error);
        }
        debug_assert!(self.headers.len() <= self.limits.max_header_count());
        debug_assert!(self.header_bytes <= self.limits.max_header_bytes());
        debug_assert_eq!(
            self.header_bytes,
            self.headers
                .iter()
                .map(|header| header.wire_bytes)
                .sum::<usize>()
        );
        let status = self.status_code_value();
        let headers = self
            .headers
            .into_iter()
            .map(|header| {
                (
                    header.name.as_str().to_string(),
                    std::str::from_utf8(header.value.as_bytes())
                        .expect("response header values originate from UTF-8 strings")
                        .to_string(),
                )
            })
            .collect();
        let (body, stream) = match self.body {
            ResponseBody::Full(body) => (body.into_bytes()?, None),
            ResponseBody::Stream(body) => (Bytes::new(), Some(body)),
        };

        Ok(TransportResponseParts {
            status,
            headers,
            body,
            stream,
        })
    }
}

fn prepare_headers<'a, I>(
    limits: ResponseLimits,
    headers: I,
) -> Result<(SmallVec<[StoredHeader; INLINE_RESPONSE_HEADERS]>, usize), ResponseWriteError>
where
    I: IntoIterator<Item = (&'a str, &'a str)>,
{
    let mut prepared_headers = SmallVec::<[StoredHeader; INLINE_RESPONSE_HEADERS]>::new();
    let mut prepared_header_bytes = 0usize;
    for (name, value) in headers {
        let (name, value, wire_bytes) = validate_header(name, value, limits.max_header_bytes())?;
        if prepared_headers.iter().any(|header| header.name == name)
            && is_singleton_response_header(&name)
        {
            return Err(ResponseHeaderError::DuplicateSingleton.into());
        }

        let next_count =
            prepared_headers
                .len()
                .checked_add(1)
                .ok_or(ResponseHeaderError::TooManyHeaders {
                    limit: limits.max_header_count(),
                })?;
        ensure_header_count(next_count, limits.max_header_count())?;
        let next_bytes = prepared_header_bytes.checked_add(wire_bytes).ok_or(
            ResponseHeaderError::HeadersTooLarge {
                limit_bytes: limits.max_header_bytes(),
            },
        )?;
        ensure_header_bytes(next_bytes, limits.max_header_bytes())?;

        prepared_headers.push(StoredHeader {
            name,
            value,
            wire_bytes,
        });
        prepared_header_bytes = next_bytes;
    }
    Ok((prepared_headers, prepared_header_bytes))
}

fn parse_header_name(name: &str) -> Result<HeaderName, ResponseHeaderError> {
    // Bound a lookup or mutation name before `http` canonicalizes it.
    header_wire_bytes(name.len(), 0, HARD_MAX_RESPONSE_HEADER_BYTES)?;
    HeaderName::from_bytes(name.as_bytes()).map_err(|_| ResponseHeaderError::InvalidName)
}

fn validate_header(
    name: &str,
    value: &str,
    max_header_bytes: usize,
) -> Result<(HeaderName, HeaderValue, usize), ResponseHeaderError> {
    // Run the allocation-free syntax, ownership, and individual-size checks
    // before `http` canonicalizes the name or copies the value.
    let wire_bytes = validate_response_header_input_with_limit(name, value, max_header_bytes)?;
    let name = parse_header_name(name)?;
    let value =
        HeaderValue::try_from(value.to_owned()).map_err(|_| ResponseHeaderError::InvalidValue)?;
    Ok((name, value, wire_bytes))
}

/// Validates one application response header without retaining or cloning any
/// caller-provided input. `ResponseBuilder` uses this before it owns dynamic
/// names and values, while `Response` repeats the check at its mutation
/// boundary as defense in depth.
pub(crate) fn validate_response_header_input(
    name: &str,
    value: &str,
) -> Result<usize, ResponseHeaderError> {
    validate_response_header_input_with_limit(name, value, HARD_MAX_RESPONSE_HEADER_BYTES)
}

fn validate_response_header_input_with_limit(
    name: &str,
    value: &str,
    max_header_bytes: usize,
) -> Result<usize, ResponseHeaderError> {
    let wire_bytes = header_wire_bytes(name.len(), value.len(), max_header_bytes)?;

    if name.is_empty() || !name.bytes().all(is_header_name_byte) {
        return Err(ResponseHeaderError::InvalidName);
    }
    ensure_application_managed_header_name(name)?;

    // Match `http::HeaderValue`: HTAB, visible ASCII, and obs-text are valid;
    // every other control byte (including CR/LF and DEL) is rejected.
    if !value
        .bytes()
        .all(|byte| byte == b'\t' || (byte >= b' ' && byte != 0x7f))
    {
        return Err(ResponseHeaderError::InvalidValue);
    }

    Ok(wire_bytes)
}

#[inline]
fn is_header_name_byte(byte: u8) -> bool {
    byte.is_ascii_alphanumeric()
        || matches!(
            byte,
            b'!' | b'#'
                | b'$'
                | b'%'
                | b'&'
                | b'\''
                | b'*'
                | b'+'
                | b'-'
                | b'.'
                | b'^'
                | b'_'
                | b'`'
                | b'|'
                | b'~'
        )
}

fn ensure_application_managed_header(name: &HeaderName) -> Result<(), ResponseHeaderError> {
    ensure_application_managed_header_name(name.as_str())
}

fn ensure_application_managed_header_name(name: &str) -> Result<(), ResponseHeaderError> {
    if name.eq_ignore_ascii_case("content-length") || name.eq_ignore_ascii_case("server") {
        return Err(ResponseHeaderError::TransportControlled);
    }
    if [
        "connection",
        "keep-alive",
        "proxy-connection",
        "te",
        "trailer",
        "transfer-encoding",
        "upgrade",
    ]
    .iter()
    .any(|forbidden| name.eq_ignore_ascii_case(forbidden))
    {
        return Err(ResponseHeaderError::HopByHop);
    }
    Ok(())
}

fn header_wire_bytes(
    name_bytes: usize,
    value_bytes: usize,
    max_header_bytes: usize,
) -> Result<usize, ResponseHeaderError> {
    let wire_bytes = name_bytes
        .checked_add(2)
        .and_then(|bytes| bytes.checked_add(value_bytes))
        .and_then(|bytes| bytes.checked_add(2))
        .ok_or(ResponseHeaderError::HeadersTooLarge {
            limit_bytes: max_header_bytes,
        })?;
    ensure_header_bytes(wire_bytes, max_header_bytes)?;
    Ok(wire_bytes)
}

fn ensure_header_count(count: usize, max_headers: usize) -> Result<(), ResponseHeaderError> {
    if count > max_headers {
        return Err(ResponseHeaderError::TooManyHeaders { limit: max_headers });
    }
    Ok(())
}

fn ensure_header_bytes(bytes: usize, max_header_bytes: usize) -> Result<(), ResponseHeaderError> {
    if bytes > max_header_bytes {
        return Err(ResponseHeaderError::HeadersTooLarge {
            limit_bytes: max_header_bytes,
        });
    }
    Ok(())
}

/// Returns whether the field has single-value response semantics. This string
/// form lets `ResponseBuilder` reject a duplicate before owning dynamic input.
pub(crate) fn is_singleton_response_header_name(name: &str) -> bool {
    [
        "content-type",
        "content-location",
        "content-range",
        "location",
        "retry-after",
        "age",
        "date",
        "etag",
        "expires",
        "last-modified",
        "strict-transport-security",
        "x-content-type-options",
        "x-frame-options",
        "access-control-allow-origin",
        "access-control-allow-credentials",
        "access-control-max-age",
    ]
    .iter()
    .any(|singleton| name.eq_ignore_ascii_case(singleton))
}

/// RFC field definitions determine whether duplicate field lines are valid.
/// This bounded list contains response fields whose grammar is a single value
/// and fields where duplicate ambiguity is security-sensitive. Unknown
/// extension fields remain appendable. `Set-Cookie`, `Vary`, `Link`,
/// authentication challenges, and other repeatable fields are intentionally
/// absent.
fn is_singleton_response_header(name: &HeaderName) -> bool {
    is_singleton_response_header_name(name.as_str())
}

