/// Default number of application response header field lines.
///
/// Repeated `Set-Cookie` fields count individually. Transport-owned fields,
/// such as generated `Content-Length` and `Server`, are outside this
/// application-level limit and cannot be inserted through [`Response`].
pub const DEFAULT_MAX_RESPONSE_HEADERS: usize = 64;

/// Default aggregate wire bytes for application response header field lines.
///
/// Accounting includes each field's name, `: ` separator, value, and trailing
/// CRLF. The final empty line and transport-owned fields are not included.
pub const DEFAULT_MAX_RESPONSE_HEADER_BYTES: usize = 64 * 1024;

/// Framework safety ceiling for configured application response headers.
pub const HARD_MAX_RESPONSE_HEADERS: usize = 1024;

/// Framework safety ceiling for retained application response header bytes.
pub const HARD_MAX_RESPONSE_HEADER_BYTES: usize = 1024 * 1024;

const INLINE_RESPONSE_HEADERS: usize = 8;

/// A fail-closed response-header mutation error.
///
/// Neither this error's `Debug` nor `Display` output contains caller-provided
/// header names or values, because either may carry sensitive data.
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
#[non_exhaustive]
pub enum ResponseHeaderError {
    /// The field name is not a valid HTTP header name.
    #[error("response header name is invalid")]
    InvalidName,
    /// The field value contains bytes forbidden by the HTTP grammar.
    #[error("response header value is invalid")]
    InvalidValue,
    #[error("response header count exceeds the configured limit of {limit}")]
    /// Adding the field would exceed the effective field-line count.
    TooManyHeaders {
        /// Effective maximum field-line count.
        limit: usize,
    },
    /// Adding the field would exceed the effective aggregate wire-byte limit.
    #[error("response header bytes exceed the configured limit of {limit_bytes}")]
    HeadersTooLarge {
        /// Effective maximum aggregate wire bytes.
        limit_bytes: usize,
    },
    /// The field is a singleton and was already present.
    #[error("response header does not permit duplicate field lines")]
    DuplicateSingleton,
    /// The field is generated by Lily's transport rather than applications.
    #[error("response header is controlled by the HTTP transport")]
    TransportControlled,
    /// Hop-by-hop fields cannot be forwarded through an application response.
    #[error("hop-by-hop response headers are not accepted from applications")]
    HopByHop,
}

/// A typed, secret-safe failure while writing or deleting a response cookie.
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
#[non_exhaustive]
pub enum ResponseCookieWriteError {
    /// Cookie construction or serialization failed.
    #[error(transparent)]
    Cookie(#[from] ResponseCookieError),
    /// Inserting the serialized `Set-Cookie` field failed.
    #[error(transparent)]
    Header(#[from] ResponseHeaderError),
}

impl From<ResponseCookieWriteError> for HttpApiError {
    fn from(error: ResponseCookieWriteError) -> Self {
        HttpApiError::ResponseEncodingError(error.to_string())
    }
}

/// A stable, payload-free buffered or streaming response-body failure.
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
#[non_exhaustive]
pub enum ResponseBodyError {
    /// A buffered body exceeded its effective byte budget.
    #[error("response body exceeds the configured {limit_bytes}-byte limit")]
    LimitExceeded {
        /// Effective body limit.
        limit_bytes: usize,
    },
    /// Body-length arithmetic overflowed.
    #[error("response body length overflowed the configured {limit_bytes}-byte limit")]
    LengthOverflow {
        /// Effective body limit.
        limit_bytes: usize,
    },
    /// Allocation failed before exceeding the configured bound.
    #[error("response body allocation failed within the configured {limit_bytes}-byte limit")]
    AllocationFailed {
        /// Effective body limit.
        limit_bytes: usize,
    },
    /// Buffered and streaming writers were selected for the same response.
    #[error("buffered and streaming response body modes cannot be mixed")]
    BodyModeConflict,
    /// The configured per-chunk limit is zero.
    #[error("response stream chunk limit must be greater than zero")]
    InvalidStreamChunkLimit,
    /// The configured cumulative stream limit is zero.
    #[error("response stream cumulative limit must be greater than zero when configured")]
    InvalidStreamTotalLimit,
    #[error(
        "response stream produced a chunk larger than the configured {limit_bytes}-byte limit"
    )]
    /// A source emitted a chunk larger than the effective per-chunk limit.
    StreamChunkTooLarge {
        /// Effective per-chunk limit.
        limit_bytes: usize,
    },
    /// Cumulative emitted bytes exceeded the effective stream limit.
    #[error("response stream exceeded the configured {limit_bytes}-byte cumulative limit")]
    StreamLimitExceeded {
        /// Effective cumulative stream limit.
        limit_bytes: u64,
    },
    /// Emitted bytes exceeded the stream's declared exact length.
    #[error("response stream exceeded its declared {expected_bytes}-byte length")]
    StreamLengthExceeded {
        /// Declared exact length.
        expected_bytes: u64,
    },
    /// The stream ended before its declared exact length.
    #[error(
        "response stream ended after {actual_bytes} bytes instead of its declared {expected_bytes} bytes"
    )]
    StreamLengthIncomplete {
        /// Declared exact length.
        expected_bytes: u64,
        /// Bytes emitted before the stream ended.
        actual_bytes: u64,
    },
    /// The application stream returned an error whose payload is deliberately discarded.
    #[error("response stream source failed")]
    StreamSourceFailed,
    /// The retained HTTP producer was stopped before completion.
    #[error("response stream was interrupted")]
    StreamInterrupted,
}

impl ResponseBodyError {
    /// Stable, payload-free diagnostic code used after response headers commit.
    #[must_use]
    pub const fn error_code(self) -> &'static str {
        match self {
            Self::LimitExceeded { .. } => "RESPONSE_BODY_LIMIT_EXCEEDED",
            Self::LengthOverflow { .. } => "RESPONSE_BODY_LENGTH_OVERFLOW",
            Self::AllocationFailed { .. } => "RESPONSE_BODY_ALLOCATION_FAILED",
            Self::BodyModeConflict => "RESPONSE_BODY_MODE_CONFLICT",
            Self::InvalidStreamChunkLimit => "RESPONSE_STREAM_CHUNK_LIMIT_INVALID",
            Self::InvalidStreamTotalLimit => "RESPONSE_STREAM_TOTAL_LIMIT_INVALID",
            Self::StreamChunkTooLarge { .. } => "RESPONSE_STREAM_CHUNK_TOO_LARGE",
            Self::StreamLimitExceeded { .. } => "RESPONSE_STREAM_LIMIT_EXCEEDED",
            Self::StreamLengthExceeded { .. } => "RESPONSE_STREAM_LENGTH_EXCEEDED",
            Self::StreamLengthIncomplete { .. } => "RESPONSE_STREAM_LENGTH_INCOMPLETE",
            Self::StreamSourceFailed => "RESPONSE_STREAM_SOURCE_FAILED",
            Self::StreamInterrupted => "RESPONSE_STREAM_INTERRUPTED",
        }
    }
}

impl From<Infallible> for ResponseBodyError {
    fn from(error: Infallible) -> Self {
        match error {}
    }
}

impl From<std::io::Error> for ResponseBodyError {
    /// Maps an application I/O source failure without retaining its potentially
    /// sensitive path, endpoint, or operating-system message.
    fn from(_error: std::io::Error) -> Self {
        Self::StreamSourceFailed
    }
}

impl From<BodyBudgetError> for ResponseBodyError {
    fn from(error: BodyBudgetError) -> Self {
        match error {
            BodyBudgetError::LimitExceeded { limit_bytes } => Self::LimitExceeded { limit_bytes },
            BodyBudgetError::LengthOverflow { limit_bytes } => Self::LengthOverflow { limit_bytes },
            BodyBudgetError::InvalidLimit { limit_bytes, .. } => {
                Self::LimitExceeded { limit_bytes }
            }
        }
    }
}

impl From<ResponseBodyError> for HttpApiError {
    fn from(error: ResponseBodyError) -> Self {
        HttpApiError::ResponseEncodingError(error.to_string())
    }
}

